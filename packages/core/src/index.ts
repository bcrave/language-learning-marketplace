// A Class Session is a fixed-time, 60-minute occurrence, so its end follows from
// its start alone. Attendance, feedback and rating windows, and reporting all hang
// off this instant.
const CLASS_SESSION_DURATION_MILLISECONDS = 60 * 60_000;

export function classSessionEndsAt(startsAt: Date) {
  return new Date(startsAt.getTime() + CLASS_SESSION_DURATION_MILLISECONDS);
}

/**
 * The latest start instant a Class Session can have and already be treated as
 * completed at `now`. Reporting needs the rule in this direction so a whole range
 * of Class Sessions can be divided into completed and still-upcoming without
 * examining them one at a time.
 */
export function latestCompletedClassSessionStart(now: Date) {
  return new Date(now.getTime() - CLASS_SESSION_DURATION_MILLISECONDS);
}

const BOOKING_DEADLINE_MILLISECONDS = 30 * 60_000;
const REFUND_DEADLINE_MILLISECONDS = 24 * 60 * 60_000;
const WAITLIST_DEADLINE_MILLISECONDS = 2 * 60 * 60_000;

export function bookingWindowIsOpen(now: Date, startsAt: Date) {
  return startsAt.getTime() - now.getTime() >= BOOKING_DEADLINE_MILLISECONDS;
}

export function studentCancellationCreditOutcome(now: Date, startsAt: Date) {
  const timeUntilStart = startsAt.getTime() - now.getTime();
  if (timeUntilStart <= 0) return "CLOSED" as const;
  return timeUntilStart >= REFUND_DEADLINE_MILLISECONDS
    ? "REFUND" as const
    : "FORFEIT" as const;
}

export function waitlistExpiresAt(startsAt: Date) {
  return new Date(startsAt.getTime() - WAITLIST_DEADLINE_MILLISECONDS);
}

export function waitlistIsOpen(now: Date, startsAt: Date) {
  return now < waitlistExpiresAt(startsAt);
}

// A Cohort membership and a Sponsorship both cover the half-open instant range
// [start, end): activity exactly at the end instant already falls outside, so
// ending either one is prospective and leaves earlier attribution untouched.
export interface CohortMembershipWindow {
  cohortId: string;
  effectiveFrom: Date;
  effectiveUntil: Date | null;
}

export function cohortMembershipIsEffectiveAt(membership: CohortMembershipWindow, at: Date) {
  return membership.effectiveFrom.getTime() <= at.getTime()
    && (membership.effectiveUntil === null || at.getTime() < membership.effectiveUntil.getTime());
}

export function attributedCohortIds(memberships: readonly CohortMembershipWindow[], occurredAt: Date) {
  const attributed = memberships
    .filter((membership) => cohortMembershipIsEffectiveAt(membership, occurredAt))
    .map((membership) => membership.cohortId);
  return [...new Set(attributed)].sort();
}

export function cohortMembershipWindowsOverlap(first: CohortMembershipWindow, second: CohortMembershipWindow) {
  const firstEnd = first.effectiveUntil?.getTime() ?? Number.POSITIVE_INFINITY;
  const secondEnd = second.effectiveUntil?.getTime() ?? Number.POSITIVE_INFINITY;
  return first.effectiveFrom.getTime() < secondEnd && second.effectiveFrom.getTime() < firstEnd;
}

export function sponsorshipReportingIncludes(
  sponsorship: { acceptedAt: Date; endedAt: Date | null },
  occurredAt: Date,
) {
  return cohortMembershipIsEffectiveAt(
    { cohortId: "", effectiveFrom: sponsorship.acceptedAt, effectiveUntil: sponsorship.endedAt },
    occurredAt,
  );
}

// Attendance Rate is Attended outcomes over every recorded outcome. Unrecorded
// attendance is neither Attended nor No-show, so it stays out of the ratio and is
// disclosed beside it as an excluded count instead of depressing the rate.
export function attendanceRatePercentage(counts: { attendedCount: number; noShowCount: number }) {
  const recordedCount = counts.attendedCount + counts.noShowCount;
  return recordedCount === 0 ? null : Math.round(100 * counts.attendedCount / recordedCount);
}

// Student Cancellation Rate is Student Cancellations over those cancellations plus
// every recorded Attendance outcome. A Class Session Cancellation or a Reschedule
// ends a Booking without the Student giving up the seat, so neither appears on
// either side, and Unrecorded attendance stays out of the denominator exactly as it
// does for the Attendance Rate.
export function studentCancellationRatePercentage(counts: {
  studentCancellationCount: number;
  attendedCount: number;
  noShowCount: number;
}) {
  const total = counts.studentCancellationCount + counts.attendedCount + counts.noShowCount;
  return total === 0 ? null : Math.round(100 * counts.studentCancellationCount / total);
}

// The reported timing of a Student Cancellation shares the 24-hour boundary the
// Class Credit return uses but is not the same fact: a Teacher Substitution or a
// fresh waitlist promotion returns the credit for a cancellation that was still
// late, so the rate must read the clock rather than the refund. It is a separate
// constant for that reason, and reporting reads it directly to divide a whole range
// of cancellations at once.
export const STUDENT_CANCELLATION_TIMELY_WINDOW_MILLISECONDS = 24 * 60 * 60_000;

export function studentCancellationTiming(cancelledAt: Date, startsAt: Date) {
  return startsAt.getTime() - cancelledAt.getTime() >= STUDENT_CANCELLATION_TIMELY_WINDOW_MILLISECONDS
    ? "TIMELY" as const
    : "LATE" as const;
}

// An exception-first report leads with what needs attention rather than with the
// activity that went as expected.
export function reportExceptionCount(counts: {
  noShowCount: number;
  excludedUnrecordedCount: number;
  correctedCount: number;
}) {
  return counts.noShowCount + counts.excludedUnrecordedCount + counts.correctedCount;
}

export interface CourseProgressValue {
  completedActiveLessonUnitCount: number;
  activeLessonUnitCount: number;
}

export function courseProgressPercentage(completedActiveLessonUnitCount: number, activeLessonUnitCount: number) {
  return activeLessonUnitCount === 0
    ? 0
    : Math.round(100 * completedActiveLessonUnitCount / activeLessonUnitCount);
}

// Between two frozen boundaries both sides share the same frozen active-unit
// denominator, so only a revised completion fact can move the gain. Against a live
// current value the denominator is the one in force now, because an active
// Sponsorship reports a current aggregate rather than a frozen one. Either way a
// removed completion yields a negative gain rather than a rewritten baseline.
export function courseProgressGain(baseline: CourseProgressValue, ending: CourseProgressValue) {
  return {
    completedLessonUnitGain: ending.completedActiveLessonUnitCount - baseline.completedActiveLessonUnitCount,
    percentagePointGain: courseProgressPercentage(ending.completedActiveLessonUnitCount, ending.activeLessonUnitCount)
      - courseProgressPercentage(baseline.completedActiveLessonUnitCount, baseline.activeLessonUnitCount),
  };
}

